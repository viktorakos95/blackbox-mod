#!/usr/bin/env python3
"""Link step helper (build.sh): splits the objects into the core (bank 1) and the machines (bank 2, src/b2.h), and writes
  out/b2stubs.S   a bank 1 stub for every function the core calls in a machine object: asks b2_gate(), then jumps to the real one (renamed b2r_<name>) or, unpaired, returns 0
  out/cave.ld     the linker script (src/cave.ld.in with the object lists filled in)
usage: b2link.py <machine object names, space separated> -- <all objects>"""
import fnmatch
import re
import subprocess
import sys

args = sys.argv[1:]
i = args.index("--")
MACH = set(args[:i])
OBJS = args[i + 1:]                        # out/obj/<name>.o (and out/munchi.o)
name = lambda o: o.rsplit("/", 1)[-1][:-2]
mach_objs = [o for o in OBJS if name(o) in MACH]
core_objs = [o for o in OBJS if name(o) not in MACH]


def nm(o):
    d, u = set(), set()
    for l in subprocess.check_output(["arm-none-eabi-nm", o], text=True).split("\n"):
        p = l.split()
        if len(p) == 3 and p[1] in "TtDdBbRrWw":
            d.add(p[2])
        elif len(p) == 2 and p[0] == "U":
            u.add(p[1])
    return d, u


mdef, cund = set(), set()
for o in mach_objs:
    mdef |= nm(o)[0]
for o in core_objs:
    cund |= nm(o)[1]
cross = sorted(mdef & cund)               # the core calls these: they become stubs in bank 1
for o in mach_objs:
    if cross:
        subprocess.check_call(["arm-none-eabi-objcopy"] + [f"--redefine-sym={s}=b2r_{s}" for s in cross] + [o])

# what the core's call does when bank 2 is not paired (default: nothing, returns 0 - also 0.0 for a float)
FALLBACK = {
    "looper_in": "    ldr     r12, =0x080518f1             /* stock's input stage, the call the hook replaced (patches/looper.py) */\n    bx      r12\n",
    "looper_status": "    bx      lr                           /* returns its argument: the label text is as it was */\n",
    "looper_page_next": "    mvn     r0, #0\n    bx      lr\n",
}
DEFAULT_FB = "    movs    r0, #0\n    vmov    s0, r0\n    bx      lr\n"
with open("out/b2stubs.S", "w") as f:
    f.write("""/* GENERATED by tools/b2link.py: bank 1 stubs for the machines' functions the core calls (src/b2.h). Unpaired: see FALLBACK there (default: returns 0). */
    .syntax unified
    .thumb
    .text
""")
    for s_ in cross:
        f.write(f"""    .global {s_}
    .thumb_func
    .type {s_}, %function
{s_}:
    push    {{r0, r1, r2, r3, r12, lr}}
    vpush   {{s0-s15}}
    bl      b2_gate
    vpop    {{s0-s15}}
    str     r0, [sp, #16]
    pop     {{r0, r1, r2, r3, r12, lr}}
    cmp     r12, #0
    beq     1f
    ldr     r12, =b2r_{s_}
    bx      r12
1:
{FALLBACK.get(s_, DEFAULT_FB)}    .ltorg
""")
cross_unknown = [k for k in FALLBACK if k not in cross]
assert not cross_unknown, f"FALLBACK for symbols the core does not call: {cross_unknown}"
print(f"b2link: {len(mach_objs)} machine objects, {len(core_objs)} core, {len(cross)} gated entries", file=sys.stderr)

globs = [l.strip() for l in open("src/itcm.list") if l.strip() and not l.startswith("#")]


def itcm_sections(o):
    out = subprocess.check_output(["arm-none-eabi-objdump", "-h", o], text=True)
    secs = [m.group(1) for m in re.finditer(r"^\s*\d+\s+(\S+)\s+[0-9a-f]+", out, re.M)]
    return [s for s in secs if any(fnmatch.fnmatchcase(s, g) for g in globs)]


def pat(objs, which):
    lines = []
    for o in objs:
        secs = itcm_sections(o)
        if secs:
            lines.append(f"    *{o.split('out/')[-1]}({' '.join(secs)})" if False else f"    {o}({' '.join(secs)})")
    return "\n".join(lines)


def flash(objs):
    return "\n".join(f"    {o}(.text .text.* .rodata .rodata.*)" for o in objs)


stub_obj = ["out/obj/b2stubs.o"]
t = open("src/cave.ld.in").read()
t = t.replace("@ITCM_CORE@", pat(core_objs, "core")).replace("@ITCM_MACH@", pat(mach_objs, "mach"))
t = t.replace("@CAVE_OBJS@", flash(core_objs + stub_obj)).replace("@B2_OBJS@", flash(mach_objs))
open("out/cave.ld", "w").write(t)
